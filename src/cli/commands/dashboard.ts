/**
 * `execos dashboard` — launch / stop the local SvelteKit web dashboard.
 *
 * Lifecycle architecture (architecture/constitution.md R15–R17;
 * architecture/decisions/010-dashboard-lifecycle.md):
 *   - The running server is discovered, not bookkept: `start`, `stop`, and
 *     `status` probe `GET /api/health` on the dashboard port and trust the
 *     `app` identity string plus the pid the server reports about itself.
 *   - The pidfile (`.cache/dashboard.pid`) is written by the serving process
 *     itself (the `dashboard serve` foreground owner), never by the launcher.
 *     It is a fallback hint for `stop` and the installer, not a source of
 *     truth.
 *   - On Windows the server is spawned through WMI (`Win32_Process.Create`),
 *     which parents it under the WMI provider host — outside any terminal,
 *     agent sandbox, or job object that launched the CLI. The dashboard must
 *     never die because its creator's session ended.
 *   - Single-instance is enforced by the port bind itself; only one process
 *     can listen on the dashboard port.
 *   - There is no idle shutdown. The server is stateless and stays up all day.
 *
 * Default port 3737 (overridable via `EXECOS_DASHBOARD_PORT` / `DASHBOARD_PORT`).
 * Prefers the production server generated by `vite build` (build-web/); falls
 * back to the Vite dev server when no build exists or a rebuild failed.
 */

import { spawn, spawnSync } from "node:child_process";
import {
  closeSync,
  existsSync,
  mkdirSync,
  openSync,
  readdirSync,
  readFileSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { createConnection } from "node:net";
import { platform } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import type { Command } from "commander";

const DEFAULT_PORT = 3737;

/**
 * Identity contract string. Must match the literal returned by
 * `src/web/routes/api/health/+server.ts`.
 */
export const DASHBOARD_APP_ID = "execos-dashboard";

export interface DashboardPaths {
  lockfile: string;
  repoRoot: string;
}

export function dashboardPaths(): DashboardPaths {
  const here = dirname(fileURLToPath(import.meta.url));
  const repoRoot = resolve(here, "..", "..", "..");
  const lockfile = join(repoRoot, ".cache", "dashboard.pid");
  return { lockfile, repoRoot };
}

/**
 * Read a PID from the lockfile. Returns null if missing, malformed, or
 * the recorded process is no longer alive (in which case the stale file
 * is cleared as a side effect).
 */
export function readLivePid(lockfilePath: string): number | null {
  if (!existsSync(lockfilePath)) return null;
  let raw: string;
  try {
    raw = readFileSync(lockfilePath, "utf8").trim();
  } catch {
    return null;
  }
  const pid = Number.parseInt(raw, 10);
  if (!Number.isFinite(pid) || pid <= 0) {
    try {
      unlinkSync(lockfilePath);
    } catch {
      /* ignore */
    }
    return null;
  }
  if (!isProcessAlive(pid)) {
    try {
      unlinkSync(lockfilePath);
    } catch {
      /* ignore */
    }
    return null;
  }
  return pid;
}

export function isProcessAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch (err: unknown) {
    if (err && typeof err === "object" && "code" in err && err.code === "EPERM") {
      // Process exists but we lack permission to signal it.
      return true;
    }
    return false;
  }
}

function writePidFile(lockfilePath: string, pid: number): void {
  mkdirSync(dirname(lockfilePath), { recursive: true });
  writeFileSync(lockfilePath, String(pid), "utf8");
}

function readTail(path: string, maxChars = 2000): string {
  try {
    const text = readFileSync(path, "utf8");
    return text.length > maxChars ? text.slice(-maxChars) : text;
  } catch {
    return "";
  }
}

function printLogTail(label: string, path: string): void {
  const tail = readTail(path).trim();
  if (!tail) return;
  console.error(`${label} (${path}):`);
  console.error(tail);
}

function urlFor(port: number): string {
  return `http://localhost:${port}`;
}

function dashboardPort(): number {
  return Number(process.env.DASHBOARD_PORT ?? process.env.EXECOS_DASHBOARD_PORT ?? DEFAULT_PORT);
}

export function isLocalPortReachable(
  port: number,
  host = "127.0.0.1",
  timeoutMs = 250,
): Promise<boolean> {
  return new Promise((resolve) => {
    const socket = createConnection({ host, port });
    let settled = false;

    const finish = (reachable: boolean) => {
      if (settled) return;
      settled = true;
      socket.destroy();
      resolve(reachable);
    };

    socket.setTimeout(timeoutMs);
    socket.once("connect", () => finish(true));
    socket.once("timeout", () => finish(false));
    socket.once("error", () => finish(false));
  });
}

export interface DashboardHealth {
  app: string;
  pid: number;
  started_at: string;
  env_kind: string | null;
}

/** Parse a health-endpoint payload; null unless it identifies our dashboard. */
export function parseDashboardHealth(body: unknown): DashboardHealth | null {
  if (!body || typeof body !== "object") return null;
  const record = body as Record<string, unknown>;
  if (record.app !== DASHBOARD_APP_ID) return null;
  const pid = Number(record.pid);
  if (!Number.isFinite(pid) || pid <= 0) return null;
  return {
    app: DASHBOARD_APP_ID,
    pid,
    started_at: typeof record.started_at === "string" ? record.started_at : "",
    env_kind: typeof record.env_kind === "string" ? record.env_kind : null,
  };
}

/**
 * Probe the dashboard's identity endpoint. Returns the health payload when
 * the listener on `port` is a ExecOS dashboard, null when the port is
 * closed, times out, or is held by some other process.
 */
export async function fetchDashboardHealth(
  port: number,
  timeoutMs = 1500,
): Promise<DashboardHealth | null> {
  try {
    const res = await fetch(`http://127.0.0.1:${port}/api/health`, {
      signal: AbortSignal.timeout(timeoutMs),
    });
    if (!res.ok) return null;
    return parseDashboardHealth(await res.json());
  } catch {
    return null;
  }
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Wait until the health endpoint answers twice in a row (catches
 * listen-then-crash). `wrapperPid` is the detached wrapper process; if it
 * dies while the port is still silent we fail fast instead of burning the
 * whole timeout.
 */
async function waitForDashboardHealthy(
  port: number,
  wrapperPid: number | null,
  timeoutMs = 30_000,
): Promise<DashboardHealth | null> {
  const deadline = Date.now() + timeoutMs;
  const startedAt = Date.now();
  while (Date.now() < deadline) {
    const health = await fetchDashboardHealth(port, 1000);
    if (health) {
      await sleep(500);
      const confirm = await fetchDashboardHealth(port, 1000);
      if (confirm) return confirm;
    }
    const wrapperDead = wrapperPid !== null && !isProcessAlive(wrapperPid);
    if (wrapperDead && Date.now() - startedAt > 3000 && !(await isLocalPortReachable(port))) {
      return null;
    }
    await sleep(300);
  }
  return null;
}

function psLiteral(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function viteDevCommand(repoRoot: string, port: number): { command: string; args: string[] } {
  const viteBin = join(repoRoot, "node_modules", "vite", "bin", "vite.js");
  return {
    command: process.execPath,
    args: [viteBin, "dev", "--host", "127.0.0.1", "--port", String(port), "--strictPort"],
  };
}

export function dashboardServerCommand(repoRoot: string, port: number): {
  command: string;
  args: string[];
} {
  const productionServer = join(repoRoot, "build-web", "index.js");
  if (existsSync(productionServer)) {
    return { command: process.execPath, args: [productionServer] };
  }
  return viteDevCommand(repoRoot, port);
}

/** Newest mtime (ms) of any file under `dir`, or 0 if unreadable. */
function newestMtimeUnder(dir: string): number {
  let newest = 0;
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return newest;
  }
  for (const name of names) {
    const full = join(dir, name);
    try {
      const stats = statSync(full);
      newest = stats.isDirectory()
        ? Math.max(newest, newestMtimeUnder(full))
        : Math.max(newest, stats.mtimeMs);
    } catch {
      /* ignore unreadable entries */
    }
  }
  return newest;
}

/**
 * The built dashboard (build-web/) is preferred at runtime, but it goes stale
 * whenever src/web changes — which would serve old UI or the wrong sandbox/live
 * badge. Returns true when there is no build, or any web source file is newer
 * than the build entrypoint.
 */
export function webBuildIsStale(repoRoot: string): boolean {
  const buildEntry = join(repoRoot, "build-web", "index.js");
  if (!existsSync(buildEntry)) return true;
  const webSrc = join(repoRoot, "src", "web");
  if (!existsSync(webSrc)) return false;
  return newestMtimeUnder(webSrc) > statSync(buildEntry).mtimeMs;
}

/** Rebuild the web dashboard from source. Returns true on success. */
function rebuildWeb(repoRoot: string): boolean {
  const viteBin = join(repoRoot, "node_modules", "vite", "bin", "vite.js");
  if (!existsSync(viteBin)) return false;
  const result = spawnSync(process.execPath, [viteBin, "build"], {
    cwd: repoRoot,
    stdio: "inherit",
    env: process.env,
  });
  return result.status === 0;
}

export function browserOpenCommand(
  url: string,
  os = platform(),
): { command: string; args: string[] } {
  if (os === "win32") {
    return { command: "cmd.exe", args: ["/c", "start", "", url] };
  }
  if (os === "darwin") {
    return { command: "open", args: [url] };
  }
  return { command: "xdg-open", args: [url] };
}

function runCommand(
  command: string,
  args: string[],
  env: NodeJS.ProcessEnv = process.env,
): Promise<{ code: number | null; stdout: string; stderr: string }> {
  return new Promise((resolve) => {
    const child = spawn(command, args, { env, windowsHide: true });
    let stdout = "";
    let stderr = "";
    child.stdout?.on("data", (chunk) => {
      stdout += String(chunk);
    });
    child.stderr?.on("data", (chunk) => {
      stderr += String(chunk);
    });
    child.once("error", (err) => {
      resolve({ code: 1, stdout, stderr: err.message });
    });
    child.once("close", (code) => {
      resolve({ code, stdout, stderr });
    });
  });
}

async function findPidsListeningOnPort(port: number): Promise<number[]> {
  const os = platform();
  let result: { code: number | null; stdout: string; stderr: string };

  if (os === "win32") {
    result = await runCommand("powershell.exe", [
      "-NoProfile",
      "-Command",
      `$ErrorActionPreference='SilentlyContinue'; Get-NetTCPConnection -LocalPort ${port} -State Listen | Select-Object -ExpandProperty OwningProcess -Unique`,
    ]);
  } else {
    result = await runCommand("lsof", ["-ti", `tcp:${port}`]);
  }

  if (result.code !== 0 && result.stdout.trim().length === 0) {
    return [];
  }

  return result.stdout
    .split(/\s+/)
    .map((value) => Number.parseInt(value, 10))
    .filter((pid) => Number.isFinite(pid) && pid > 0 && pid !== process.pid);
}

/**
 * The force-kill command for a PID on Windows (tree kill). Null on POSIX, where
 * forceStopPid uses process.kill signals instead.
 */
export function forceStopCommand(
  pid: number,
  os: NodeJS.Platform = platform(),
): { command: string; args: string[] } | null {
  if (os === "win32") {
    return { command: "taskkill.exe", args: ["/PID", String(pid), "/T", "/F"] };
  }
  return null;
}

async function forceStopPid(pid: number): Promise<boolean> {
  if (platform() === "win32") {
    // taskkill without /F cannot terminate a windowless node server, so the
    // dashboard is always stopped forcefully on Windows. The server is
    // stateless; there is nothing to flush.
    const result = await runCommand("taskkill.exe", ["/PID", String(pid), "/T", "/F"]);
    // A target that vanished mid-kill (tree died from a child kill, or it was
    // already exiting) is a success, not a failure.
    return result.code === 0 || !isProcessAlive(pid);
  }

  try {
    // The serve process is spawned detached (its own process group); kill the
    // group so a Vite dev child dies with it. Fall back to the single pid.
    try {
      process.kill(-pid, "SIGTERM");
    } catch {
      process.kill(pid, "SIGTERM");
    }
    return true;
  } catch {
    try {
      process.kill(pid, "SIGKILL");
      return true;
    } catch {
      return false;
    }
  }
}

/** Arguments for the foreground `dashboard serve` owner process. */
export function serveCommandArgs(
  repoRoot: string,
  port: number,
  preferVite: boolean,
): { command: string; args: string[] } {
  const launcher = join(repoRoot, "scripts", "execos.mjs");
  const args = [launcher, "dashboard", "serve", "--port", String(port)];
  if (preferVite) args.push("--prefer-vite");
  return { command: process.execPath, args };
}

/**
 * The full `cmd.exe` command line handed to `Win32_Process.Create` on
 * Windows. The cmd wrapper exists only to redirect server output into the
 * log files; it lives exactly as long as the node process under it.
 */
export function windowsDetachedCommandLine(
  serve: { command: string; args: string[] },
  stdoutPath: string,
  stderrPath: string,
): string {
  const quoted = [serve.command, ...serve.args].map((part) => `"${part}"`).join(" ");
  return `cmd.exe /d /s /c "${quoted} 1>> "${stdoutPath}" 2>> "${stderrPath}""`;
}

/**
 * Spawn the serve process on Windows via WMI so it is parented under the WMI
 * provider host instead of this CLI's process tree. This is what lets the
 * dashboard outlive agent sandboxes, terminal windows, and job objects.
 * Returns the wrapper pid, or null on failure.
 */
async function spawnDetachedWindows(
  commandLine: string,
  currentDirectory: string,
): Promise<number | null> {
  const script = [
    "$ErrorActionPreference='Stop'",
    "$sui = New-CimInstance -ClassName Win32_ProcessStartup -ClientOnly -Property @{ ShowWindow = [UInt16]0 }",
    `$r = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = ${psLiteral(commandLine)}; CurrentDirectory = ${psLiteral(currentDirectory)}; ProcessStartupInformation = $sui }`,
    'if ($r.ReturnValue -ne 0) { throw "Win32_Process.Create failed with return value $($r.ReturnValue)" }',
    "$r.ProcessId",
  ].join("; ");
  const result = await runCommand("powershell.exe", ["-NoProfile", "-Command", script]);
  if (result.code !== 0) {
    if (result.stderr.trim()) console.error(result.stderr.trim());
    return null;
  }
  const pid = Number.parseInt(result.stdout.trim(), 10);
  return Number.isFinite(pid) && pid > 0 ? pid : null;
}

/**
 * POSIX detachment (also the Windows fallback if WMI creation fails):
 * detached process group with output to the log files.
 */
function spawnDetachedDefault(
  serve: { command: string; args: string[] },
  repoRoot: string,
  stdoutPath: string,
  stderrPath: string,
): number | null {
  const out = openSync(stdoutPath, "a");
  const err = openSync(stderrPath, "a");
  try {
    const child = spawn(serve.command, serve.args, {
      cwd: repoRoot,
      detached: true,
      env: process.env,
      stdio: ["ignore", out, err],
      windowsHide: true,
    });
    child.unref();
    return typeof child.pid === "number" ? child.pid : null;
  } finally {
    closeSync(out);
    closeSync(err);
  }
}

/**
 * Foreground server owner (`execos dashboard serve`). Runs under the daily
 * launcher so the target env file is loaded; writes its own pid to the
 * lockfile; serves the production build in-process, or a Vite dev child when
 * no usable build exists.
 */
async function serveDashboard(options: { port?: string; preferVite?: boolean }): Promise<number> {
  const { lockfile, repoRoot } = dashboardPaths();
  const port = options.port ? Number(options.port) : dashboardPort();
  if (!Number.isFinite(port) || port <= 0) {
    console.error(`Invalid dashboard port: ${options.port}`);
    return 1;
  }

  if (await fetchDashboardHealth(port)) {
    console.error(`A dashboard is already serving on ${urlFor(port)}; refusing to double-serve.`);
    return 1;
  }

  process.env.HOST = "127.0.0.1";
  process.env.PORT = String(port);
  process.env.DASHBOARD_PORT = String(port);

  writePidFile(lockfile, process.pid);
  process.once("exit", () => {
    try {
      if (readFileSync(lockfile, "utf8").trim() === String(process.pid)) unlinkSync(lockfile);
    } catch {
      /* ignore */
    }
  });

  const productionServer = join(repoRoot, "build-web", "index.js");
  if (!options.preferVite && existsSync(productionServer)) {
    // adapter-node starts listening as a side effect of the import and keeps
    // the event loop (and therefore this process) alive.
    await import(pathToFileURL(productionServer).href);
    console.log(`Dashboard serving (pid ${process.pid}) on ${urlFor(port)}.`);
    return 0;
  }

  const vite = viteDevCommand(repoRoot, port);
  if (!existsSync(vite.args[0])) {
    console.error("Dashboard dependencies are missing. Run npm install, then retry.");
    return 1;
  }
  const child = spawn(vite.command, vite.args, {
    cwd: repoRoot,
    env: process.env,
    stdio: "inherit",
    windowsHide: true,
  });
  const stopChild = () => {
    try {
      child.kill("SIGTERM");
    } catch {
      /* ignore */
    }
  };
  process.once("SIGINT", stopChild);
  process.once("SIGTERM", stopChild);
  console.log(`Dashboard serving via Vite dev (pid ${process.pid}) on ${urlFor(port)}.`);
  return await new Promise<number>((resolveExit) => {
    child.once("close", (code) => resolveExit(code ?? 1));
  });
}

async function startDashboard(): Promise<number> {
  const { lockfile, repoRoot } = dashboardPaths();
  const port = dashboardPort();
  const url = urlFor(port);

  const existing = await fetchDashboardHealth(port);
  if (existing) {
    console.log(`Dashboard already running (pid ${existing.pid}) on ${url}`);
    await tryOpenBrowser(url);
    return 0;
  }

  if (await isLocalPortReachable(port)) {
    console.error(`Port ${port} is in use by a process that is not the ExecOS dashboard.`);
    console.error(
      `Stop that process, or set EXECOS_DASHBOARD_PORT to a free port, then retry.`,
    );
    return 1;
  }

  console.log(`Starting dashboard on ${url}...`);

  // Never serve a stale dashboard: if the build is older than the web source,
  // rebuild it so the UI and the sandbox/live badge match the current code. If
  // the rebuild fails, serve falls back to the always-fresh Vite dev server.
  let preferVite = false;
  if (webBuildIsStale(repoRoot)) {
    console.log("Dashboard build is out of date; rebuilding it once (this can take ~30s)...");
    if (!rebuildWeb(repoRoot)) {
      console.warn("Dashboard rebuild failed; serving the live Vite dev server instead.");
      preferVite = true;
    }
  }

  mkdirSync(dirname(lockfile), { recursive: true });
  const stdoutPath = join(repoRoot, ".cache", "dashboard.out.log");
  const stderrPath = join(repoRoot, ".cache", "dashboard.err.log");
  for (const logPath of [stdoutPath, stderrPath]) {
    try {
      unlinkSync(logPath);
    } catch {
      /* ignore */
    }
  }

  const serve = serveCommandArgs(repoRoot, port, preferVite);
  let wrapperPid: number | null = null;
  if (platform() === "win32") {
    wrapperPid = await spawnDetachedWindows(
      windowsDetachedCommandLine(serve, stdoutPath, stderrPath),
      repoRoot,
    );
    if (wrapperPid === null) {
      console.warn(
        "Detached (WMI) spawn failed; starting attached instead. The dashboard may not survive this session ending.",
      );
      wrapperPid = spawnDetachedDefault(serve, repoRoot, stdoutPath, stderrPath);
    }
  } else {
    wrapperPid = spawnDetachedDefault(serve, repoRoot, stdoutPath, stderrPath);
  }

  if (wrapperPid === null) {
    console.error("Failed to spawn dashboard process.");
    return 1;
  }

  const health = await waitForDashboardHealthy(port, wrapperPid);
  if (!health) {
    console.error(`Dashboard did not become healthy on ${url}.`);
    printLogTail("Dashboard stdout", stdoutPath);
    printLogTail("Dashboard stderr", stderrPath);
    // Best-effort cleanup of whatever the spawn left behind.
    if (isProcessAlive(wrapperPid)) await forceStopPid(wrapperPid);
    const staleServerPid = readLivePid(lockfile);
    if (staleServerPid !== null) await forceStopPid(staleServerPid);
    return 1;
  }

  console.log(`Dashboard launched (pid ${health.pid}) on ${url}.`);
  console.log("Stop it with: execos dashboard stop");
  await tryOpenBrowser(url);
  return 0;
}

async function stopDashboard(force = false): Promise<number> {
  const { lockfile } = dashboardPaths();
  const port = dashboardPort();

  const targets = new Set<number>();
  const health = await fetchDashboardHealth(port);
  if (health) targets.add(health.pid);
  const recorded = readLivePid(lockfile);
  if (recorded !== null) targets.add(recorded);
  if (force) {
    for (const pid of await findPidsListeningOnPort(port)) targets.add(pid);
  }

  if (targets.size === 0) {
    console.log("No dashboard process found.");
    if (await isLocalPortReachable(port)) {
      console.log(
        `Port ${port} is in use by a process that is not the ExecOS dashboard. ` +
          "Run: execos dashboard stop --force to kill the listener anyway.",
      );
    }
    return 0;
  }

  const list = [...targets];
  const results = await Promise.all(list.map((pid) => forceStopPid(pid)));
  try {
    unlinkSync(lockfile);
  } catch {
    /* ignore */
  }

  const stopped = list.filter((_, index) => results[index]);
  // The kill is asynchronous on Windows; confirm the port actually frees up.
  const deadline = Date.now() + 5000;
  let released = false;
  while (Date.now() < deadline) {
    if (!(await isLocalPortReachable(port))) {
      released = true;
      break;
    }
    await sleep(250);
  }

  if (stopped.length > 0 && released) {
    console.log(`Stopped dashboard process(es): ${stopped.join(", ")}. Port ${port} released.`);
    return 0;
  }
  if (!released) {
    console.error(`Port ${port} is still in use after stopping ${stopped.join(", ") || "nothing"}.`);
    console.error("Run: execos dashboard stop --force");
    return 1;
  }
  console.error(`Failed to stop dashboard process(es): ${list.join(", ")}.`);
  return 1;
}

async function dashboardStatus(): Promise<number> {
  const port = dashboardPort();
  const health = await fetchDashboardHealth(port);
  if (health) {
    const since = health.started_at ? ` since ${health.started_at}` : "";
    const env = health.env_kind ? ` [${health.env_kind}]` : "";
    console.log(`Dashboard running (pid ${health.pid})${env} on ${urlFor(port)}${since}.`);
    return 0;
  }
  if (await isLocalPortReachable(port)) {
    console.log(`Port ${port} is in use, but not by the ExecOS dashboard.`);
    return 1;
  }
  console.log("Dashboard is not running.");
  return 1;
}

async function tryOpenBrowser(url: string): Promise<void> {
  const opener = browserOpenCommand(url);
  try {
    await new Promise<void>((resolve, reject) => {
      const child = spawn(opener.command, opener.args, {
        stdio: "ignore",
        windowsHide: true,
      });
      child.once("error", reject);
      child.once("close", (code) => {
        if (code === 0) resolve();
        else reject(new Error(`${opener.command} exited with code ${code}`));
      });
    });
  } catch {
    console.log(`Open this URL manually: ${url}`);
  }
}

export function registerDashboardCommand(program: Command): void {
  const dash = program.command("dashboard").description("Launch / stop the local web dashboard");

  dash
    .command("start", { isDefault: true })
    .description("Start the dashboard (idempotent — second call detects existing instance)")
    .action(async () => {
      const code = await startDashboard();
      if (code !== 0) process.exitCode = code;
    });

  dash
    .command("stop")
    .description("Stop the running dashboard process")
    .option("-f, --force", "Also kill an unrecorded process listening on the dashboard port")
    .action(async (options: { force?: boolean }) => {
      const code = await stopDashboard(Boolean(options.force));
      if (code !== 0) process.exitCode = code;
    });

  dash
    .command("status")
    .description("Report whether a dashboard is serving on the configured port")
    .action(async () => {
      const code = await dashboardStatus();
      if (code !== 0) process.exitCode = code;
    });

  dash
    .command("serve")
    .description("Run the dashboard server in the foreground (used internally by start)")
    .option("--port <port>", "Port to listen on")
    .option("--prefer-vite", "Serve via the Vite dev server even if a build exists")
    .action(async (options: { port?: string; preferVite?: boolean }) => {
      const code = await serveDashboard(options);
      if (code !== 0) process.exitCode = code;
    });
}
