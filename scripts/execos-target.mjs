#!/usr/bin/env node

import path from "node:path";
import { fileURLToPath } from "node:url";
import { existsSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { readEnvFile } from "./installer/env.mjs";
import {
  readTarget,
  writeTarget,
  describeTarget,
  activeEnvFile,
  LIVE_ENV_FILES,
  SANDBOX_ENV_FILE,
} from "./lib/active-target.mjs";
import { getLocalStatus } from "./lib/supabase-cli.mjs";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function targetHelpText() {
  const state = readTarget(repoRoot);
  return [
    "ExecOS target and profile help",
    "",
    `Current target:   ${describeTarget(state)}`,
    `Current env file: ${activeEnvFile(state)}`,
    "",
    "Target commands, these switch which database/env file daily uses:",
    "  npm run target              Print this help menu",
    "  npm run target:help         Print this help menu",
    "  npm run target:status       Show the active target and env file",
    "  npm run target:prod         Use .env.production.local for execos commands",
    "  npm run target:dev          Use .env.development.local for execos commands",
    "",
    "Sandbox commands, these run execos against a local clone:",
    "  npm run sandbox:start       Clone the active live target into local Supabase and use it",
    "  npm run sandbox             Alias for npm run sandbox:start",
    "  npm run sandbox:stop        Leave sandbox mode and return to the selected live target",
    "",
    "Profile commands, these switch prompts, skills, and operational contracts:",
    "  .\\scripts\\apply-profile.ps1 -Profile production",
    "  .\\scripts\\apply-profile.ps1 -Profile developer",
    "",
    "Rule of thumb:",
    "  Profile switches prompts and skills.",
    "  Target switches the database/env file used by execos commands.",
    "",
    "Common flows:",
    "  Test production profile against production data:",
    "    .\\scripts\\apply-profile.ps1 -Profile production",
    "    npm run target:prod",
    "",
    "  Test production profile safely in a local clone of production:",
    "    .\\scripts\\apply-profile.ps1 -Profile production",
    "    npm run target:prod",
    "    npm run sandbox:start",
    "",
    "  Return to developer profile and development data:",
    "    .\\scripts\\apply-profile.ps1 -Profile developer",
    "    npm run target:dev",
  ].join("\n");
}

function cmdHelp() {
  console.log(targetHelpText());
}

function cmdStatus() {
  const state = readTarget(repoRoot);
  console.log(`Target:   ${describeTarget(state)}`);
  console.log(`Env file: ${activeEnvFile(state)}`);
  if (state.sandbox.active) {
    console.log(`Source:   ${state.sandbox.source}`);
    console.log(`Cloned:   ${state.sandbox.clonedAt}`);
  }
}

function cmdUse(env) {
  if (env !== "development" && env !== "production") {
    console.error("Usage: node scripts/execos-target.mjs use <development|production>");
    process.exit(1);
  }
  const state = readTarget(repoRoot);
  state.live = env;
  state.sandbox = { active: false, source: null, clonedAt: null };
  writeTarget(repoRoot, state);
  console.log(`Live target set to ${env}; sandbox OFF. Now: ${describeTarget(state)}`);
}

function cmdSandboxStart() {
  const state = readTarget(repoRoot);
  const sourceEnvFile = LIVE_ENV_FILES[state.live];
  const sourceEnvPath = path.join(repoRoot, sourceEnvFile);
  if (!existsSync(sourceEnvPath)) {
    console.error(`Active live env file ${sourceEnvFile} not found. Set one with target:prod/target:dev.`);
    process.exit(1);
  }

  console.log(`[sandbox] cloning the active target (${state.live}) into the local stack...`);
  const clone = spawnSync(
    "node",
    ["scripts/run-with-env.cjs", sourceEnvFile, "node", "scripts/clone-to-local.mjs"],
    { cwd: repoRoot, stdio: "inherit" },
  );
  if (clone.status !== 0) {
    console.error("[sandbox] clone failed; sandbox NOT activated.");
    process.exit(1);
  }

  const local = getLocalStatus(repoRoot);
  const source = readEnvFile(sourceEnvPath);
  const lines = [
    "# Generated by scripts/execos-target.mjs sandbox-start. Do not commit. Local stack only.",
    `DATABASE_URL="${local.DB_URL}"`,
    `SUPABASE_URL="${local.API_URL}"`,
    `SUPABASE_ANON_KEY="${local.ANON_KEY}"`,
    `SUPABASE_SERVICE_ROLE_KEY="${local.SERVICE_ROLE_KEY}"`,
    `OPENAI_API_KEY="${source.OPENAI_API_KEY ?? ""}"`,
    `EXECOS_DASHBOARD_PORT="${source.EXECOS_DASHBOARD_PORT ?? source.DASHBOARD_PORT ?? "4317"}"`,
    `EMBEDDING_DIMENSION="${source.EMBEDDING_DIMENSION ?? "3072"}"`,
    "",
  ];
  writeFileSync(path.join(repoRoot, SANDBOX_ENV_FILE), lines.join("\n"));

  const clonedAt = new Date().toISOString().slice(0, 16).replace("T", " ");
  state.sandbox = { active: true, source: state.live, clonedAt };
  writeTarget(repoRoot, state);

  console.log("");
  console.log(`SANDBOX MODE ON. Every execos command now hits the LOCAL CLONE of ${state.sandbox.source}.`);
  console.log("Studio: http://127.0.0.1:54323   |   Stop with: npm run sandbox:stop");
}

function cmdSandboxStop() {
  const state = readTarget(repoRoot);
  state.sandbox = { active: false, source: null, clonedAt: null };
  writeTarget(repoRoot, state);
  console.log(`SANDBOX MODE OFF. Now: ${describeTarget(state)}`);
}

const [sub, arg] = process.argv.slice(2);
switch (sub) {
  case undefined:
  case "help":
  case "--help":
  case "-h":
    cmdHelp();
    break;
  case "status":
    cmdStatus();
    break;
  case "use":
    cmdUse(arg);
    break;
  case "sandbox-start":
    cmdSandboxStart();
    break;
  case "sandbox-stop":
    cmdSandboxStop();
    break;
  default:
    console.error(`Unknown target command: ${sub}`);
    console.error("");
    console.error(targetHelpText());
    process.exit(1);
}
