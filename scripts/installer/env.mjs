import { chmodSync, existsSync, mkdirSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

export const ENV_ORDER = [
  "EXECOS_DB_ENV",
  "SUPABASE_URL",
  "SUPABASE_PROJECT_NAME",
  "SUPABASE_SERVICE_ROLE_KEY",
  "SUPABASE_ANON_KEY",
  "DATABASE_URL",
  "OPENAI_API_KEY",
  "DASHBOARD_PORT",
  "USER_DEFAULT_TIMEZONE",
  "EXECOS_INSTALL_VALIDATED_STEPS",
];

export function stripInlineComment(rawValue) {
  let inSingle = false;
  let inDouble = false;
  for (let i = 0; i < rawValue.length; i += 1) {
    const char = rawValue[i];
    if (char === "'" && !inDouble) {
      inSingle = !inSingle;
      continue;
    }
    if (char === '"' && !inSingle) {
      const escaped = i > 0 && rawValue[i - 1] === "\\";
      if (!escaped) inDouble = !inDouble;
      continue;
    }
    if (char === "#" && !inSingle && !inDouble) {
      const previous = i === 0 ? "" : rawValue[i - 1];
      if (i === 0 || /\s/.test(previous)) {
        return rawValue.slice(0, i).trimEnd();
      }
    }
  }
  return rawValue;
}

export function unquoteEnvValue(rawValue) {
  const trimmed = rawValue.trim();
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1).replace(/\\"/g, '"').replace(/\\\\/g, "\\");
  }
  return trimmed;
}

export function readEnvFile(path) {
  const values = {};
  if (!existsSync(path)) return values;
  const lines = readFileSync(path, "utf8").split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    values[key] = unquoteEnvValue(stripInlineComment(trimmed.slice(eq + 1)));
  }
  return values;
}

export function formatEnvLine(key, value) {
  const escaped = String(value ?? "").replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `${key}="${escaped}"`;
}

export function envFileText(values, order = ENV_ORDER, generatedBy = "scripts/install.sh") {
  const lines = [
    "# ExecOS repo-local environment configuration",
    `# Generated by ${generatedBy}. Do not commit this file.`,
    "# MCP integration credentials are managed by the agent harness, not this installer.",
    "",
  ];
  for (const key of order) {
    if (Object.prototype.hasOwnProperty.call(values, key)) {
      lines.push(formatEnvLine(key, values[key]));
    }
  }
  return `${lines.join("\n")}\n`;
}

export function writeEnvFile(path, values, options = {}) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, envFileText(values, options.order ?? ENV_ORDER, options.generatedBy), {
    encoding: "utf8",
    mode: 0o600,
  });
  try {
    chmod600(path);
  } catch {
    // chmod is best effort on mounted Windows filesystems.
  }
}

export function writeEnvFileAtomically(path, values, options = {}) {
  const tempPath = `${path}.installing-final-${process.pid}.tmp`;
  const targetDir = dirname(path);
  mkdirSync(targetDir, { recursive: true });
  writeEnvFile(tempPath, values, options);
  assertSameDevice(tempPath, targetDir);
  renameSync(tempPath, path);
  try {
    chmod600(path);
  } catch {
    // chmod is best effort on mounted Windows filesystems.
  }
}

export function assertSameDevice(tempPath, targetDirectory) {
  const tempDevice = statSync(tempPath).dev;
  const targetDevice = statSync(targetDirectory).dev;
  if (tempDevice !== targetDevice) {
    throw new Error(`Refusing non-atomic env write across filesystems: ${tempPath}`);
  }
}

export function chmod600(path) {
  chmodSync(path, 0o600);
}

export function backupExistingEnv(path, now = new Date()) {
  if (!existsSync(path)) return null;
  const timestamp = formatTimestamp(now);
  const backupPath = `${path}.backup-${timestamp}`;
  writeFileSync(backupPath, readFileSync(path));
  try {
    chmod600(backupPath);
  } catch {
    // chmod is best effort on mounted Windows filesystems.
  }
  return backupPath;
}

export function formatTimestamp(date) {
  const pad = (value) => String(value).padStart(2, "0");
  return [
    date.getFullYear(),
    pad(date.getMonth() + 1),
    pad(date.getDate()),
    "-",
    pad(date.getHours()),
    pad(date.getMinutes()),
    pad(date.getSeconds()),
  ].join("");
}

export function validatedStepsFrom(values) {
  return new Set(
    String(values.EXECOS_INSTALL_VALIDATED_STEPS ?? "")
      .split(",")
      .map((value) => value.trim())
      .filter(Boolean),
  );
}

export function serializeValidatedSteps(steps) {
  return [...steps].sort().join(",");
}
